type Company = { RcoUUID: string; RcoName: string };

/** First and last day (YYYY-MM-DD) of the previous month, the usual AFD period. */
export function previousMonth(today = new Date()): { from: string; to: string } {
  const first = new Date(Date.UTC(today.getFullYear(), today.getMonth() - 1, 1));
  const last = new Date(Date.UTC(today.getFullYear(), today.getMonth(), 0));
  return { from: first.toISOString().slice(0, 10), to: last.toISOString().slice(0, 10) };
}

/** Query of the AFD export: company (empty = tenant, internal account) and the period. */
export function afdQuery(company: string, from: string, to: string): string {
  const query = new URLSearchParams({ from, to });
  if (company) query.set('companyUUID', company);
  return `hr/time-punches/afd?${query}`;
}

/**
 * AFD (Arquivo Fonte de Dados, REP-P) of one establishment: the company of the current HR account
 * (or the tenant for the internal account) and the recording period. The file is generated by the
 * API in the gov.br layout; this dialog only asks the period and saves it.
 */
@Component({
  selector: 'app-hr-afd-export-dialog',
  standalone: true,
  imports: [
    FormsModule,
    MatButtonModule,
    MatFormFieldModule,
    MatInputModule,
    MatSelectModule,
    ReportProblemButtonComponent,
    TranslocoPipe,
  ],
  template: `
    <div class="crud-dialog">
      <header class="dialog-header">
        <div>
          <h2>{{ 'Export AFD' | transloco }}</h2>
          <p>
            {{
              'Source data file (AFD, Portaria 671) of one establishment with the marks recorded in the period.'
                | transloco
            }}
          </p>
        </div>
        <mns-report-problem-button />
      </header>
      <div class="dialog-content">
        <div class="dialog-scroll">
          <form class="form-grid" (ngSubmit)="export()">
            <mat-form-field appearance="outline" class="span-1">
              <mat-label>{{ 'Establishment' | transloco }}</mat-label>
              <mat-select name="company" [(ngModel)]="company">
                <mat-option value="">{{ 'Tenant (marks without company)' | transloco }}</mat-option>
                @for (item of companies(); track item.RcoUUID) {
                  <mat-option [value]="item.RcoUUID">{{ item.RcoName }}</mat-option>
                }
              </mat-select>
            </mat-form-field>
            <mat-form-field appearance="outline" class="span-1">
              <mat-label>{{ 'Start date' | transloco }}</mat-label>
              <input matInput type="date" name="from" required [(ngModel)]="from" />
            </mat-form-field>
            <mat-form-field appearance="outline" class="span-1">
              <mat-label>{{ 'End date' | transloco }}</mat-label>
              <input matInput type="date" name="to" required [(ngModel)]="to" />
            </mat-form-field>
          </form>
          @if (notice(); as message) {
            <p class="dashboard-message" role="status">{{ message }}</p>
          }
          @if (error(); as message) {
            <p class="dashboard-message" role="alert">{{ message | transloco }}</p>
          }
        </div>
      </div>
      <div class="form-actions">
        <div class="secondary-actions">
          <button mat-stroked-button type="button" (click)="close()">
            {{ 'Close' | transloco }}
          </button>
        </div>
        <button
          mat-flat-button
          type="button"
          [disabled]="busy() || !from || !to"
          (click)="export()"
        >
          {{ (busy() ? 'Generating...' : 'Export AFD') | transloco }}
        </button>
      </div>
    </div>
  `,
})
export class AfdExportDialogComponent {
  private readonly api = inject(ApiService);
  private readonly dialogRef = inject(MatDialogRef<AfdExportDialogComponent>);
  private readonly transloco = inject(TranslocoService);

  private readonly companyList = resource({
    loader: async () => {
      const response = await this.api.get<any>('hr/companies?limit=500', { silent: true });
      const items = response?.data?.items ?? response?.data ?? [];
      return (Array.isArray(items) ? items : []) as Company[];
    },
  });
  readonly companies = computed(() =>
    this.companyList.hasValue() ? this.companyList.value() : ([] as Company[]),
  );
  readonly busy = signal(false);
  readonly error = signal<string | null>(null);
  readonly notice = signal<string | null>(null);
  company = '';
  from = previousMonth().from;
  to = previousMonth().to;

  async export() {
    if (this.busy() || !this.from || !this.to) return;
    this.busy.set(true);
    this.error.set(null);
    this.notice.set(null);
    try {
      const { blob, headers } = await this.api.getBlobResponse(
        afdQuery(this.company, this.from, this.to),
      );
      const name = headers.get('X-Afd-File-Name') || 'AFD.txt';
      const link = document.createElement('a');
      link.href = URL.createObjectURL(blob);
      link.download = name;
      link.click();
      setTimeout(() => URL.revokeObjectURL(link.href), 1000);
      const t = (key: string, params?: Record<string, string>) =>
        this.transloco.translate(key, params);
      const parts = [
        t('AFD generated with {{count}} marks.', { count: headers.get('X-Afd-Marks') ?? '0' }),
      ];
      if (headers.get('X-Afd-Provisional') === '1') {
        parts.push(t('Provisional file: the program has no INPI registration number yet.'));
      }
      if (Number(headers.get('X-Afd-Missing-Documents') ?? 0) > 0) {
        parts.push(
          t('{{count}} marks of employees without CPF.', {
            count: headers.get('X-Afd-Missing-Documents') ?? '0',
          }),
        );
      }
      this.notice.set(parts.join(' '));
    } catch (error) {
      const body = (error as any)?.error;
      let message = 'Failed to generate the AFD.';
      if (body instanceof Blob) {
        try {
          message = JSON.parse(await body.text())?.error || message;
        } catch {
          // Keep the generic message.
        }
      }
      this.error.set(message);
    } finally {
      this.busy.set(false);
    }
  }

  close() {
    this.dialogRef.close();
  }
}

export async function openAfdExportDialog(dialog: MatDialog) {
  const binding = openCrudComponentDialog(dialog, AfdExportDialogComponent, 'crud-form-dialog');
  try {
    await firstValueFrom(binding.ref.afterClosed());
  } finally {
    binding.stop();
  }
}
