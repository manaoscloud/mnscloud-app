const ENDPOINT = 'hr/time-clock-accounts';

const statuses = [
  { value: 'active', label: 'Active' },
  { value: 'inactive', label: 'Inactive' },
  { value: 'blocked', label: 'Blocked' },
];

type TemporaryCredential = {
  LoginCode?: string | null;
  TemporaryPassword?: string | null;
  TemporaryPasswordExpiresAt?: string | null;
  /** Access e-mail to the employee: sent, no_email, failed or skipped. */
  EmailDelivery?: string | null;
  EmailRecipient?: string | null;
};

/** What the credentials dialog says about the access e-mail sent to the employee. */
export function credentialEmailNote(credential: TemporaryCredential): string {
  switch (credential.EmailDelivery) {
    case 'sent':
      return 'The access was e-mailed to the employee. Keep these credentials only if you need to help them sign in.';
    case 'no_email':
      return 'The employee has no e-mail in the registry, so nothing was sent. Hand these credentials over securely, or add an e-mail and reset the password.';
    case 'failed':
      return 'The access e-mail could not be sent. Hand these credentials over securely, or check the SMTP route and reset the password.';
    default:
      return 'Show these credentials to the employee securely. The password is not stored here.';
  }
}

