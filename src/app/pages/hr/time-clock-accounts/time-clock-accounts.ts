@Component({
  selector: 'app-hr-time-clock-accounts',
  standalone: true,
  imports: CONFIGURABLE_CRUD_IMPORTS,
  templateUrl: '../../../shared/crud/configurable-crud/configurable-crud-page.html',
  styleUrls: ['../../../shared/crud/configurable-crud/configurable-crud-page.scss'],
})
export class HrTimeClockAccountsPage extends ConfigurableCrudPageBase<ConfigurableCrudRecord> {
  private readonly ops: HrPageOps = {
    confirm: (title, message, label) => this.confirmAction(title, message, label),
    post: (path, body) => this.api.post(path, body),
    success: (message) => this.snack.success(this.t(message)),
    failure: (error, fallback) => this.snack.error(this.t(this.errorMessage(error) || fallback)),
    refresh: () => this.refreshList(),
  };

  private readonly route = inject(ActivatedRoute);

  constructor() {
    super(config);
    afterNextRender(() => void this.openForEmployee());
  }

  /**
   * Employee registry › Pulse access: open the employee's account, or the create form with the
   * employee preset when they have none yet.
   */
  private async openForEmployee(): Promise<void> {
    const params = this.route.snapshot.queryParamMap;
    const employeeUUID = params.get('employeeUUID')?.trim();
    if (!employeeUUID) return;
    const employeeName = params.get('employeeName')?.trim() || employeeUUID;
    try {
      const response = await this.api.get<{ data?: { items?: ConfigurableCrudRecord[] } }>(
        `${ENDPOINT}?employeeUUID=${encodeURIComponent(employeeUUID)}&limit=1&offset=0`,
      );
      const account = response?.data?.items?.[0];
      if (account) {
        this.search.set(String(account['LoginCode'] ?? employeeName));
        this.applySearchFilters();
        this.snack.info(
          this.t(
            'This employee already has Pulse access. Use Reset password to send new credentials.',
          ),
        );
        return;
      }
    } catch {
      // The create form below still works; the API refuses a duplicate account.
    }
    if (!this.canCreate()) return;
    this.presetRemoteOption('employeeUUID', {
      value: employeeUUID,
      label: employeeName,
      searchText: `${employeeName} ${employeeUUID}`,
    });
    this.startCreateWithValues({ employeeUUID });
  }

  protected override afterSave(context: ConfigurableCrudSaveContext<ConfigurableCrudRecord>): void {
    if (context.mode !== 'create') return;
    const credential = (context.response as { data?: TemporaryCredential } | null)?.data;
    if (credential?.TemporaryPassword) this.showCredential(credential);
  }

  override async handleRowAction(
    action: ConfigurableCrudRowAction,
    row: ConfigurableCrudRecord,
  ): Promise<void> {
    if (action.key === 'endSessions') {
      await this.endSessions(row);
      return;
    }
    if (action.key === 'kioskPin' || action.key === 'clearKioskPin') {
      await this.kioskPin(row, action.key === 'clearKioskPin');
      return;
    }
    if (action.key !== 'resetPassword') return;
    const confirmed = await this.confirmAction(
      'Reset password',
      'Generate a new temporary password? The previous password stops working immediately.',
      'Reset password',
    );
    if (!confirmed) return;
    try {
      const response = await this.api.post<{ data?: TemporaryCredential }>(
        `${ENDPOINT}/${row['TimeClockAccountUUID']}/reset-password`,
        {},
      );
      this.snack.success(this.t('Temporary password generated successfully.'));
      this.refreshList();
      this.showCredential({ ...response?.data, LoginCode: String(row['LoginCode'] ?? '') });
    } catch (error) {
      this.snack.error(this.t(this.errorMessage(error) || 'Failed to reset password.'));
    }
  }

  private async endSessions(row: ConfigurableCrudRecord): Promise<void> {
    await confirmedPost(
      this.ops,
      'End sessions',
      'Sign the employee out of Pulse on every device? They must sign in again to punch.',
      `${ENDPOINT}/${row['TimeClockAccountUUID']}/sessions/revoke`,
      {},
      'Pulse sessions ended.',
      'Failed to end the sessions.',
    );
  }

  /**
   * Time clock PIN (company time clocks of the Pulse kiosk mode): a new random PIN shown once, or
   * cleared so the employee sets a new one in Pulse.
   */
  private async kioskPin(row: ConfigurableCrudRecord, clear: boolean): Promise<void> {
    const confirmed = await this.confirmAction(
      clear ? 'Clear time clock PIN' : 'Generate time clock PIN',
      clear
        ? 'Clear the time clock PIN? The employee can no longer punch on the company time clocks until a new PIN is set in Pulse or generated here.'
        : 'Generate a new time clock PIN? The previous PIN stops working immediately.',
      clear ? 'Clear time clock PIN' : 'Generate time clock PIN',
    );
    if (!confirmed) return;
    const path = `${ENDPOINT}/${row['TimeClockAccountUUID']}/kiosk-pin`;
    try {
      if (clear) {
        await this.api.delete(path);
        this.snack.success(this.t('Time clock PIN cleared.'));
        return;
      }
      const pin = randomKioskPin();
      await this.api.put(path, { pin });
      showHrSecret(
        this.dialog,
        'Time clock PIN',
        'Give this PIN to the employee securely. It is used with the login code on the company time clocks and is not shown again; the employee can change it in Pulse.',
        [
          { label: 'Employee', value: String(row['EmployeeName'] ?? ''), translate: false },
          this.loginCodeDetail(String(row['LoginCode'] ?? '')),
        ],
        pin,
      );
    } catch (error) {
      this.snack.error(this.t(this.errorMessage(error) || 'Failed to save the time clock PIN.'));
    }
  }

  private showCredential(credential: TemporaryCredential): void {
    const details: DataViewerDetail[] = [];
    if (credential.EmailDelivery === 'sent' && credential.EmailRecipient) {
      details.push({
        label: 'Sent to',
        value: credential.EmailRecipient,
        translate: false,
      });
    }
    showHrSecret(
      this.dialog,
      'Temporary credentials',
      credentialEmailNote(credential),
      [
        ...details,
        this.loginCodeDetail(credential.LoginCode ?? ''),
        {
          label: 'Expires at',
          value: credential.TemporaryPasswordExpiresAt ?? '',
          kind: 'datetime',
        },
      ],
      credential.TemporaryPassword ?? '',
      'Temporary password',
    );
  }

  private loginCodeDetail(value: string): DataViewerDetail {
    return { label: 'Login code', value, monospace: true, translate: false };
  }
}
