@Component({
  selector: 'app-vps-vpn-connections',
  standalone: true,
  imports: CONFIGURABLE_CRUD_IMPORTS,
  templateUrl: '../../../../shared/crud/configurable-crud/configurable-crud-page.html',
  styleUrls: ['../../../../shared/crud/configurable-crud/configurable-crud-page.scss'],
})
export class HostingVpsVpnConnectionsPage extends ConfigurableCrudPageBase<ConfigurableCrudRecord> {
  private readonly routerIps = signal<ConfigurableCrudRecord[]>([]);
  private readonly routers = signal<ConfigurableCrudRecord[]>([]);
  private readonly networks = signal<ConfigurableCrudRecord[]>([]);

  constructor() {
    super({
      ...config,
      fields: [
        {
          key: 'zoneUUID',
          source: 'HostingVpsTenantZoneHtzUUID',
          payloadKey: 'zoneUUID',
          label: 'Router',
          type: 'select',
          span: 1,
          // Only a tenant with routers on several providers chooses it, and only on create.
          hiddenWhen: ({ editing }) => editing || this.routers().length <= 1,
          requiredWhen: ({ editing }) => !editing && this.routers().length > 1,
        },
        ...(config.fields ?? []),
      ],
      columns: [
        ...(config.columns ?? []).slice(0, 3),
        {
          id: 'psk',
          label: 'Pre-shared key',
          kind: 'secret',
          copyable: true,
          secretLoader: async (row) => {
            const response = await this.api.post<{ data?: { psk?: string } }>(
              `hosting/vps/router/vpn-connections/${row['HvcUUID']}/psk/reveal`,
              {},
            );
            return String(response?.data?.psk ?? '');
          },
        },
        ...(config.columns ?? []).slice(3),
      ],
      rowActions: [
        {
          key: 'rotate',
          label: 'New pre-shared key',
          icon: 'key',
          request: {
            method: 'post',
            endpoint: (row) => `hosting/vps/router/vpn-connections/${row['HvcUUID']}/psk/rotate`,
            successMessage: 'New pre-shared key generated. Put it on your device.',
            confirm: {
              title: 'New pre-shared key',
              message:
                'The tunnel stays down until your device gets the new key. Generate a new key?',
              confirmLabel: 'Generate',
            },
          },
        } satisfies ConfigurableCrudRowAction,
        {
          key: 'portal-publish',
          label: 'Publish in the Customer Portal',
          icon: 'public',
          visible: (row) =>
            !!row['RegCustomerRcuUUID'] && Number(row['HvcPortalEnabled'] ?? 0) !== 1,
          request: {
            method: 'put',
            endpoint: (row) => `hosting/vps/router/vpn-connections/${row['HvcUUID']}/portal`,
            // Only the publication: the customer stays as the server has it.
            body: () => ({ portalEnabled: true }),
            successMessage: 'Published in the Customer Portal.',
            confirm: {
              title: 'Publish in the Customer Portal',
              message:
                'The customer sees this connection, downloads the configuration of its device and, with the key rule, reveals the pre-shared key. Publish?',
              confirmLabel: 'Publish',
            },
          },
        } satisfies ConfigurableCrudRowAction,
        {
          key: 'portal-hide',
          label: 'Hide from the Customer Portal',
          icon: 'public_off',
          visible: (row) => Number(row['HvcPortalEnabled'] ?? 0) === 1,
          request: {
            method: 'put',
            endpoint: (row) => `hosting/vps/router/vpn-connections/${row['HvcUUID']}/portal`,
            body: () => ({ portalEnabled: false }),
            successMessage: 'Hidden from the Customer Portal.',
          },
        } satisfies ConfigurableCrudRowAction,
        ...VENDORS.map(
          (vendor) =>
            ({
              key: `config-${vendor.key}`,
              label: vendor.label,
              icon: 'download',
              visible: (row) => {
                const isWg = row['HvcType'] === 'wireguard';
                if (vendor.wireguardOnly && !isWg) return false;
                if (vendor.ipsecOnly && isWg) return false;
                return true;
              },
              run: (row) => this.download(row, vendor.key),
            }) satisfies ConfigurableCrudRowAction,
        ),
      ],
    });
    void this.fetchRouterState();
  }

  protected override lookupOptions(key: string): readonly ConfigurableCrudOption[] {
    const zone = this.selectedZone();
    if (key === 'zoneUUID') {
      return this.routers().map((router) => ({
        value: String(router['zoneUUID']),
        label: String(router['providerName'] ?? router['zoneUUID']),
      }));
    }
    if (key === 'publicIpUUID') {
      return this.routerIps()
        .filter((ip) => !zone || String(ip['HostingVpsTenantZoneHtzUUID'] ?? '') === zone)
        .map((ip) => ({ value: String(ip['HpiUUID']), label: String(ip['HpiAddress']) }));
    }
    if (key === 'localNetworks') {
      return this.networks()
        .filter((network) => !zone || String(network['HostingVpsTenantZoneHtzUUID'] ?? '') === zone)
        .map((network) => ({
          value: String(network['HvnUUID']),
          label: `${network['HvnName']} (${network['HvnCidr']})`,
        }));
    }
    return [];
  }

  /** Router of the form: the edited connection's, the chosen one, or the only one. */
  private selectedZone(): string {
    const editing = this.editingRecord();
    if (editing) return String(editing['HostingVpsTenantZoneHtzUUID'] ?? '');
    const chosen = String(this.formValues()['zoneUUID'] ?? '');
    if (chosen) return chosen;
    const routers = this.routers();
    return routers.length === 1 ? String(routers[0]['zoneUUID']) : '';
  }

  protected override formValuesFromRecord(row: ConfigurableCrudRecord): ConfigurableCrudRecord {
    const values = super.formValuesFromRecord(row);
    return {
      ...values,
      type: String(row['HvcType'] ?? 'ipsec'),
      wireguardPublicKey: String(row['HvcWireguardPublicKey'] ?? ''),
      wireguardListenPort: row['HvcWireguardListenPort'] ? String(row['HvcWireguardListenPort']) : '',
      bgpEnabled: String(Number(row['HvcBgpEnabled'] ?? 0) === 1 ? '1' : '0'),
      bgpLocalAsn: row['HvcBgpLocalAsn'] ? String(row['HvcBgpLocalAsn']) : '',
      bgpRemoteAsn: row['HvcBgpRemoteAsn'] ? String(row['HvcBgpRemoteAsn']) : '',
      bgpLocalPeerIp: String(row['HvcBgpLocalPeerIp'] ?? ''),
      bgpRemotePeerIp: String(row['HvcBgpRemotePeerIp'] ?? ''),
      bgpMaxPrefixes: row['HvcBgpMaxPrefixes'] ? Number(row['HvcBgpMaxPrefixes']) : 50,
      isActive: String(Number(row['HvcIsActive'] ?? 1) === 0 ? 0 : 1),
      localNetworks: lines(row['LocalNetworks']),
      remotePrefixes: lines(row['RemotePrefixes']).join('\n'),
    };
  }

  /** The customer has its own route (P1): sent after the connection saved, never before. */
  override async saveItem(saveAndNew = false): Promise<void> {
    const current = this.editingRecord();
    const chosen = current ? String(this.formValues()['customerUuid'] ?? '') || null : null;
    const previous = current ? String(current['RegCustomerRcuUUID'] ?? '') || null : null;
    await super.saveItem(saveAndNew);
    // Still editing = the save failed (the dialog shows why): the customer is left as it was.
    if (!current || this.editingRecord() === current || chosen === previous) return;
    try {
      await this.api.put(`hosting/vps/router/vpn-connections/${current['HvcUUID']}/portal`, {
        customerUUID: chosen,
        portalEnabled: false,
      });
      this.refreshList();
    } catch (error) {
      this.snack.error(this.t(this.errorMessage(error)));
    }
  }

  override refreshList() {
    void this.fetchRouterState();
    super.refreshList();
  }

  protected override augmentPayload(payload: ConfigurableCrudRecord): ConfigurableCrudRecord {
    const zone = this.selectedZone();
    const networks = payload['localNetworks'];
    const type = payload['type'] === 'wireguard' ? 'wireguard' : 'ipsec';
    const isWg = type === 'wireguard';
    const bgpEnabled = payload['bgpEnabled'] === '1';
    return {
      ...(this.editingRecord() ? {} : { zoneUUID: zone || null }),
      name: String(payload['name'] ?? '').trim(),
      type,
      publicIpUUID: payload['publicIpUUID'] || null,
      remoteAddress: String(payload['remoteAddress'] ?? '').trim() || null,
      startAction: isWg ? 'start' : payload['startAction'] || 'start',
      remoteId: isWg ? null : String(payload['remoteId'] ?? '').trim() || null,
      localId: isWg ? null : String(payload['localId'] ?? '').trim() || null,
      profile: isWg ? 'recommended' : payload['profile'] || 'recommended',
      wireguardPublicKey: isWg ? String(payload['wireguardPublicKey'] ?? '').trim() || null : null,
      wireguardListenPort: isWg && payload['wireguardListenPort'] ? Number(payload['wireguardListenPort']) : null,
      bgpEnabled,
      bgpLocalAsn: bgpEnabled && payload['bgpLocalAsn'] ? Number(payload['bgpLocalAsn']) : null,
      bgpRemoteAsn: bgpEnabled && payload['bgpRemoteAsn'] ? Number(payload['bgpRemoteAsn']) : null,
      bgpLocalPeerIp: bgpEnabled ? String(payload['bgpLocalPeerIp'] ?? '').trim() || null : null,
      bgpRemotePeerIp: bgpEnabled ? String(payload['bgpRemotePeerIp'] ?? '').trim() || null : null,
      bgpMaxPrefixes: bgpEnabled && payload['bgpMaxPrefixes'] ? Number(payload['bgpMaxPrefixes']) : 50,
      localNetworks: Array.isArray(networks) ? networks : lines(networks),
      remotePrefixes: lines(payload['remotePrefixes']),
      mtu: Number(payload['mtu']) || (isWg ? 1420 : 1400),
      dpdSeconds: isWg ? 30 : Number(payload['dpdSeconds']) || 30,
      isActive: String(payload['isActive'] ?? '1') !== '0',
      description: String(payload['description'] ?? '').trim() || null,
    };
  }

  private async download(row: ConfigurableCrudRecord, vendor: string) {
    try {
      const blob = await this.api.getBlob(
        `hosting/vps/router/vpn-connections/${row['HvcUUID']}/peer-config?vendor=${vendor}`,
      );
      const isWg = row['HvcType'] === 'wireguard';
      const ext = isWg && vendor === 'wireguard' ? 'conf' : isWg && vendor === 'mikrotik7' ? 'rsc' : 'txt';
      const url = URL.createObjectURL(blob);
      const anchor = document.createElement('a');
      anchor.href = url;
      anchor.download = `${String(row['HvcName'] ?? 'vpn')
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')}-${vendor}.${ext}`;
      anchor.click();
      setTimeout(() => URL.revokeObjectURL(url), 1000);
    } catch {
      /* the API error toast already explains the failure */
    }
  }

  private async fetchRouterState() {
    const [ips, routers, networks] = await Promise.all([
      this.api.get<{ data?: { items?: ConfigurableCrudRecord[] } }>(
        'hosting/vps/public-ips?status=allocated&limit=500',
      ),
      this.api.get<{ data?: { items?: ConfigurableCrudRecord[] } }>('hosting/vps/networks/routers'),
      this.api.get<{ data?: { items?: ConfigurableCrudRecord[] } }>(
        'hosting/vps/networks?limit=500',
      ),
    ]);
    this.routers.set(routers?.data?.items ?? []);
    this.routerIps.set(
      (ips?.data?.items ?? []).filter(
        (ip) => !!ip['HostingVpsTenantZoneHtzUUID'] && ip['HpiNetworkState'] !== 'removing',
      ),
    );
    this.networks.set(
      (networks?.data?.items ?? []).filter((network) => !!network['HostingVpsTenantZoneHtzUUID']),
    );
  }
}
