import { quickCreateFor } from '../../../shared/crud/configurable-crud/quick-create';
import { authenticationPayload, utcToLocalInput } from '../authentication-input';
import { Component, inject } from '@angular/core';
import { ApiService } from '../../../services/api.service';
import {
  CONFIGURABLE_CRUD_IMPORTS,
  ConfigurableCrudPageBase,
  ConfigurableCrudRecord,
} from '../../../shared/crud/configurable-crud/configurable-crud-page-base';
import { defineCrud } from '../../../shared/crud/configurable-crud/define-crud';

type RevealedCredential = { password?: string };

/** Username and password are generated by the API; the password is revealed only on demand. */
function accessConfig(api: ApiService) {
  return defineCrud({
    endpoint: 'authentication/accesses',
    uuidField: 'AaxUUID',
    pageTitle: 'authentication.accesses',
    pageDescription: 'authentication.accessesDescription',
    dialogDescription: 'authentication.generatedCredentialHelp',
    serverSidePagination: true,
    initialPageSize: 50,
    // Each deletion carries its own revision and dependency confirmation; no bulk deletion contract.
    bulkDelete: false,
    deletePayload: (row) => ({ revision: Number(row['AaxRevision']) }),
    initialValues: {
      notes: '',
      status: 1,
      revision: 1,
      AuthenticationAccountAacUUID: '',
      RegCustomerRcuUUID: '',
      AuthenticationProfileAapUUID: '',
      AuthenticationGroupAagUUID: '',
      AuthenticationDomainAadUUID: '',
      expiresAt: '',
      framedIp: '',
      subscriberLabel: '',
    },
    payload: (values, editing) => {
      const payload = authenticationPayload(values, editing);
      // The realm is part of the login configured in the equipment: set once, at creation.
      if (editing) delete payload['AuthenticationDomainAadUUID'];
      for (const key of ['RegCustomerRcuUUID', 'subscriberLabel'])
        if (payload[key] === '') payload[key] = null;
      return payload;
    },
    fields: [
      { key: 'status', source: 'AaxStatus', label: 'Status', type: 'status', span: 1 },
      {
        key: 'AuthenticationAccountAacUUID',
        source: 'AuthenticationAccountAacUUID',
        label: 'authentication.accounts',
        span: 1,
        required: true,
        type: 'search-select',
        remoteLookup: {
          endpoint: 'authentication/accounts',
          uuidField: 'AacUUID',
          labelField: 'AacName',
        },
        disabledWhen: ({ editing }) => editing,
        help: 'authentication.scopeHelp',
      },
      {
        key: 'RegCustomerRcuUUID',
        source: 'RegCustomerRcuUUID',
        label: 'Customer',
        span: 1,
        required: false,
        type: 'search-select',
        help: 'authentication.accessCustomerHelp',
        remoteLookup: {
          endpoint: 'registry/customers?status=1',
          searchParam: 'q',
          uuidField: 'CustomerUUID',
          labelField: 'Name',
          selectedLabelField: 'CustomerName',
        },
        quickCreate: quickCreateFor('RegCustomerRcuUUID'),
      },
      {
        key: 'AuthenticationGroupAagUUID',
        source: 'AuthenticationGroupAagUUID',
        quickCreate: quickCreateFor('AuthenticationGroupAagUUID', {
          initialValues: ({ values }) => ({
            AuthenticationAccountAacUUID: values['AuthenticationAccountAacUUID'],
          }),
        }),
        label: 'authentication.groups',
        span: 1,
        required: false,
        type: 'search-select',
        remoteLookup: {
          endpoint: 'authentication/groups',
          uuidField: 'AagUUID',
          labelField: 'AagName',
          parameters: { accountUUID: 'AuthenticationAccountAacUUID' },
          // The group default realm is suggested; a realm chosen by the operator is kept.
          fill: { AuthenticationDomainAadUUID: 'AuthenticationDomainAadUUID' },
        },
      },
      {
        key: 'AuthenticationProfileAapUUID',
        source: 'AuthenticationProfileAapUUID',
        help: 'authentication.accessProfileHelp',
        quickCreate: quickCreateFor('AuthenticationProfileAapUUID', {
          initialValues: ({ values }) => ({
            AuthenticationAccountAacUUID: values['AuthenticationAccountAacUUID'],
          }),
        }),
        label: 'authentication.profiles',
        span: 1,
        required: false,
        // The group profile is inherited (and prevails) when the selected group has one.
        requiredWhen: ({ values }) => !values['AuthenticationGroupAagUUID'],
        type: 'search-select',
        remoteLookup: {
          endpoint: 'authentication/profiles',
          uuidField: 'AapUUID',
          labelField: 'AapName',
          parameters: { accountUUID: 'AuthenticationAccountAacUUID' },
        },
      },
      {
        key: 'AuthenticationDomainAadUUID',
        source: 'AuthenticationDomainAadUUID',
        label: 'authentication.domain',
        tab: 'authentication',
        span: 1,
        required: false,
        type: 'search-select',
        help: 'authentication.accessDomainHelp',
        quickCreate: quickCreateFor('AuthenticationDomainAadUUID', {
          initialValues: ({ values }) => ({
            AuthenticationAccountAacUUID: values['AuthenticationAccountAacUUID'],
          }),
        }),
        remoteLookup: {
          endpoint: 'authentication/domains?status=1',
          uuidField: 'AadUUID',
          labelField: 'AadName',
          selectedLabelField: 'DomainName',
          parameters: { accountUUID: 'AuthenticationAccountAacUUID' },
        },
        disabledWhen: ({ editing }) => editing,
      },
      {
        key: 'subscriberLabel',
        source: 'AaxSubscriberLabel',
        label: 'authentication.subscriberLabel',
        span: 1,
        required: false,
        type: 'text',
        help: 'authentication.subscriberLabelHelp',
      },
      {
        key: 'framedIp',
        source: 'AaxFramedIp',
        label: 'authentication.framedIp',
        tab: 'authentication',
        span: 1,
        required: false,
        type: 'text',
      },
      {
        key: 'expiresAt',
        source: 'AaxExpiresAt',
        label: 'authentication.expiresAt',
        tab: 'authentication',
        span: 1,
        required: false,
        type: 'datetime',
        fromRecord: (value) => utcToLocalInput(value),
        help: 'authentication.expiryHelp',
      },
      { key: 'revision', source: 'AaxRevision', label: 'Revision', type: 'number', hidden: true },
      {
        key: 'notes',
        source: 'AaxNotes',
        label: 'Notes',
        type: 'textarea',
        tab: 'notes',
        span: 4,
        rows: 4,
      },
    ],
    columns: [
      { id: 'customer', field: 'CustomerName', label: 'Customer', kind: 'identity' },
      { id: 'subscriber', field: 'AaxSubscriberLabel', label: 'authentication.subscriberLabel', kind: 'text' },
      {
        id: 'login',
        field: 'AaxLoginName',
        label: 'authentication.login',
        kind: 'text',
        copyable: true,
      },
      {
        id: 'password',
        label: 'authentication.password',
        kind: 'secret',
        copyable: true,
        secretAvailable: (row) => Number(row['AaxHasRevealableCredential']) === 1,
        secretLoader: async (row) => {
          const response = await api.post<{ data?: RevealedCredential }>(
            `authentication/accesses/${row['AaxUUID']}/credential/reveal`,
            {},
          );
          return String(response?.data?.password ?? '');
        },
      },
      {
        id: 'account',
        field: 'AccountName',
        label: 'authentication.accounts',
        kind: 'related',
        uuidField: 'AuthenticationAccountAacUUID',
      },
      // Effective profile: the group profile when the group has one, else the access profile.
      {
        id: 'profile',
        field: 'EffectiveProfileName',
        label: 'authentication.profiles',
        kind: 'text',
      },
      { id: 'expires', field: 'AaxExpiresAt', label: 'authentication.expiresAt', kind: 'datetime' },
      { id: 'status', field: 'AaxStatus', label: 'Status', kind: 'status' },
    ],
    rowActions: [
      {
        key: 'rotate-password',
        label: 'authentication.newPassword',
        icon: 'lock_reset',
        request: {
          method: 'post',
          endpoint: (row) => `authentication/accesses/${row['AaxUUID']}/credential/rotate`,
          body: (row) => ({ revision: Number(row['AaxRevision']) }),
          successMessage: 'authentication.newPasswordGenerated',
          confirm: {
            title: 'authentication.newPassword',
            message: 'authentication.newPasswordConfirmation',
            confirmLabel: 'authentication.newPassword',
          },
        },
      },
    ],
  });
}

@Component({
  selector: 'app-accesses',
  standalone: true,
  imports: CONFIGURABLE_CRUD_IMPORTS,
  templateUrl: '../../../shared/crud/configurable-crud/configurable-crud-page.html',
  styleUrls: ['../../../shared/crud/configurable-crud/configurable-crud-page.scss'],
})
export class AuthenticationAccessPage extends ConfigurableCrudPageBase<ConfigurableCrudRecord> {
  constructor() {
    super(accessConfig(inject(ApiService)));
  }
}
